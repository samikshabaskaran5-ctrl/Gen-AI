# Use a pipeline as a high-level helper
# Note: The legacy 'translation' pipeline task was removed in transformers v5.
# Instead, we load and use the sequence-to-sequence model directly:
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

tokenizer = AutoTokenizer.from_pretrained("google-t5/t5-small")
model = AutoModelForSeq2SeqLM.from_pretrained("google-t5/t5-small", device_map="auto")

# Example usage:
text = "translate English to German: My name is Wolfgang and I live in Berlin"
inputs = tokenizer(text, return_tensors="pt").to(model.device)
outputs = model.generate(**inputs)
translation = tokenizer.decode(outputs[0], skip_special_tokens=True)
print(translation)

